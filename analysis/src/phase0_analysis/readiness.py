"""Phase 0 readiness report (plan I1), generated only from recorded evidence.

Decision rules: FAIL when any V01-V20 result is missing, not run or failing, or when
the P01 target was missed (a warning-based release needs explicit owner approval,
which this tool never grants). PASS_WITH_APPROVED_WARNINGS is produced only from an
owner approval record (``<evidence>/approvals.json``); none is created by tooling.
Otherwise PASS, with every limitation listed.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from .acceptance import V_IDS, evaluate

ROOT = Path(__file__).resolve().parents[3]

V_TITLES = {
    "V01": "WAV decode/validation support matrix", "V02": "Conversion counts, quality, endpoint disclosure",
    "V03": "Exact sample/time arithmetic", "V04": "Chunk continuity and coverage", "V05": "3-process step determinism",
    "V06": "Accelerated rational deadlines, speed validation", "V07": "Real-time replay records errors, no silent loss",
    "V08": "WER/CER goldens and pipeline", "V09": "DER/JER goldens and pipeline", "V10": "Timing joins and clock domains",
    "V11": "Bounded queue, block/drop_newest loss audit", "V12": "CPU/RSS telemetry and explicit sensor status",
    "V13": "Strict schemas, cross-language corpus", "V14": "Provenance and hashes", "V15": "Persistence, sealing, partial runs",
    "V16": "CLI end-to-end and exit codes", "V17": "Comparison compatibility", "V18": "Deterministic predictions/metrics",
    "V19": "Enforced-offline end-to-end", "V20": "Adapter contract and substitution",
}


def _load(path: Path) -> Any:
    return json.loads(path.read_text()) if path.exists() else None


def _ms(ns: float | None) -> str:
    return "—" if ns is None else f"{ns / 1e6:.2f}"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16] if path.exists() else "missing"


def decide(suite: dict, performance: dict | None, approvals: dict | None) -> tuple[str, str]:
    failing = [c["check_id"] for c in suite["checks"] if c["status"] != "pass"]
    if failing:
        return "FAIL", f"mandatory checks not passing: {', '.join(failing)}"
    if performance is None:
        return "FAIL", "performance characterization evidence is missing"
    if not performance["P01"]["target_met_all_runs"]:
        if approvals and approvals.get("p01_warning_approved"):
            return "PASS_WITH_APPROVED_WARNINGS", "P01 target missed; owner approval recorded"
        return "FAIL", "correctness passed; release pending owner approval of the P01 warning"
    if not performance.get("controlled_idle_host", False):
        return "PASS", ("all V01-V20 pass and the P01 target was met in every run, with documented limitations: "
                        "P01-P03 were measured on an uncontrolled host, so the timing results are a provisional "
                        "characterization (this is a disclosed limitation, not an owner-approved warning)")
    return "PASS", "all V01-V20 pass; P01 target met in every run on a controlled host"


def render(evidence: Path) -> tuple[str, str]:
    evidence = Path(evidence)
    suite = evaluate(evidence)
    performance = _load(evidence / "performance/characterization.json")
    determinism = _load(evidence / "determinism/equality.json")
    offline = _load(evidence / "offline/offline.json")
    control = _load(evidence / "offline/control.json")
    approvals = _load(evidence / "approvals.json")
    decision, reason = decide(suite, performance, approvals)
    by_id = {c["check_id"]: c for c in suite["checks"]}
    lines = [
        "# Phase 0 readiness report",
        "",
        f"**Decision: {decision}** — {reason}.",
        "",
        f"- **Gate A (benchmark-harness readiness): {decision}.** Generated by `phase0_analysis readiness` from "
        f"`{evidence.relative_to(ROOT) if ROOT in evidence.parents else evidence}`; suite status `{suite['status']}`.",
        "- **Gate B (real-dataset readiness): PENDING.** The English and Hindi manifests are structurally valid "
        "`pending` templates with no items; no public source, license or coverage has been verified, so no real "
        "dataset can be selected for a run. Gate B status does not change Gate A.",
        "- **Scope:** mock adapters only. All accuracy numbers validate the harness and scorers on synthetic data; "
        "none measures speech recognition or diarization quality.",
        "",
        "## Mandatory validations (V01–V20)",
        "",
        "| ID | Validation | Status | Evidence |",
        "|---|---|---|---|",
    ]
    for vid in V_IDS:
        check = by_id[vid]
        path = check["evidence"]
        lines.append(f"| {vid} | {V_TITLES[vid]} | {check['status']} | "
                     f"{'`' + str(Path(path).relative_to(ROOT)) + '`' if path and ROOT in Path(path).parents else '—'} |")
    passed = sum(1 for c in suite["checks"] if c["status"] == "pass")
    lines += ["", f"Passed {passed}/20; failed {sum(1 for c in suite['checks'] if c['status'] == 'fail')}; "
                  f"not run {sum(1 for c in suite['checks'] if c['status'] == 'not_run')}.", ""]

    lines += ["## Determinism (V05/V18)", ""]
    if determinism:
        lines.append(f"Normalizer `{determinism['normalizer']}`, {determinism['repeats']} separate processes of "
                     f"`{determinism['config']}`: **{determinism['status']}**; raw traces distinct: "
                     f"{determinism['raw_traces_distinct']}.")
        for run in determinism["runs"]:
            lines.append(f"- `{run['run_id']}`: events `{str(run.get('normalized_events_sha256'))[:16]}` "
                         f"({run.get('normalized_event_count')} projected), predictions "
                         f"`{str(run.get('predictions_projection_sha256'))[:16]}`, metrics "
                         f"`{str(run.get('metrics_projection_sha256'))[:16]}`")
    else:
        lines.append("Determinism evidence is missing.")
    lines.append("")

    lines += ["## Performance characterization (P01–P04)", ""]
    if performance:
        machine = performance["machine"]
        lines += [f"Machine: {machine['model']}, {machine['chip']}, {int(machine['memory_bytes']) / 2**30:.0f} GiB; "
                  f"`{machine['platform']}`. Controlled idle host: **{performance['controlled_idle_host']}** — "
                  f"{performance['host_note']}", "",
                  "**P01** (3 × 60 s real time, 20 ms frames; admission error = queue entry − planned deadline):", "",
                  "| Run | n | signed p50 (ms) | signed p95 (ms) | abs p95 full (ms) | abs p95 after 10 s (ms) | abs max after 10 s (ms) | wake p95 (ms) | dropped |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for run in performance["P01"]["runs"]:
            post = run["post_warmup_absolute"]
            lines.append(f"| {run['run_id']} | {run['full_signed']['n']} | {_ms(run['full_signed']['p50'])} | "
                         f"{_ms(run['full_signed']['p95'])} | {_ms(run['full_absolute']['p95'])} | {_ms(post['p95'])} | "
                         f"{_ms(post['max'])} | {_ms(run['wake_error']['p95'])} | {run['dropped_samples']:.0f} |")
        lines += ["", f"Target (post-warm-up absolute p95 ≤ 20 ms, investigatory): "
                      f"**{'met in every run' if performance['P01']['target_met_all_runs'] else 'MISSED'}**.", ""]
        p02 = performance["P02"]
        if "trend" in p02:
            lines += [f"**P02** ({p02['expected_samples'] // 16000} s real-time replay): exact media clock and accounting "
                      f"**{p02['media_clock_exact']}** ({p02['coverage']['consumed_samples']} of {p02['expected_samples']} "
                      f"samples consumed, {p02['coverage']['dropped_samples']} dropped, {p02['chunks']} chunks). Signed "
                      f"admission error trend {p02['trend']['slope_ns_per_media_second']:.1f} ns per media second (OLS, "
                      f"n={p02['trend']['n']}); final deviation {_ms(p02['final_deviation_ns'])} ms; max |deviation| "
                      f"{_ms(p02['max_abs_deviation_ns'])} ms. Absolute deadlines are re-derived from one anchor for every "
                      f"chunk, so wake latency does not accumulate. Plot: `performance/p02_drift.png`.", ""]
        else:
            lines += [f"**P02** failed: {p02.get('error')}", ""]
        lines += ["**P03** (3 paired 30 s runs, telemetry on/off, raw values only, no significance claim):", "",
                  "| Pair | order | on: runtime (ms) | off: runtime (ms) | on: abs p95 after 10 s (ms) | off: abs p95 after 10 s (ms) | on: collection (µs) |",
                  "|---|---|---:|---:|---:|---:|---:|"]
        for pair in performance["P03"]["pairs"]:
            on, off = pair.get("on", {}), pair.get("off", {})
            lines.append(f"| {pair['pair']} | {'/'.join(pair['order'])} | {_ms(on.get('runtime_total_ns'))} | "
                         f"{_ms(off.get('runtime_total_ns'))} | {_ms((on.get('post_warmup_absolute') or {}).get('p95'))} | "
                         f"{_ms((off.get('post_warmup_absolute') or {}).get('p95'))} | "
                         f"{(on.get('telemetry_collection_ns') or 0) / 1e3:.0f} |")
        lines += ["", "**P04** (telemetry completeness, telemetry-on runs):", "",
                  "| Run | samples | periodic / expected | missed intervals | max lateness (ms) | CPU % p50 | RSS peak (MiB) |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
        for run in performance["P04"]["runs"]:
            s = run["sampler"]
            lines.append(f"| {run['run_id']} | {s['samples']} | {s['periodic_samples']} / {s['expected_periodic_samples']} | "
                         f"{s['missed_intervals']} | {_ms(s['max_lateness_ns'])} | "
                         f"{run['cpu_percent']['p50']:.1f} | {run['rss_peak_sampled_bytes'] / 2**20:.1f} |")
        lines += ["", "GPU, ANE and power are `unsupported` in every run (no public per-process counter in the v1 baseline); "
                      "thermal state is the OS-reported enum, whose `nominal` can also mean unsupported.", ""]
    else:
        lines += ["Performance evidence is missing.", ""]

    lines += ["## Offline operation (V19)", ""]
    if offline and control:
        lines += [f"Policy `{control['policy']}` via `{control['sandbox_exec']}`. Positive control (local listener, no "
                  f"sandbox): `{control['outside_sandbox_local_listener']}`; inside the sandbox: "
                  f"`{control['inside_sandbox_local_listener']}`; outbound 1.1.1.1:443 inside: "
                  f"`{control['inside_sandbox_outbound_1_1_1_1_443']}`. Enforced: **{control['denial_enforced']}**. "
                  f"Full e2e under the policy: **{offline.get('e2e_status')}** ({offline.get('e2e_steps')} steps); "
                  f"model/hub caches empty afterwards: {offline['model_and_hub_caches_empty_after']}.", ""]
    else:
        lines += ["Offline evidence is missing.", ""]

    lines += ["## Evidence identities", "",
              f"- Schema bundle frozen record: `{(ROOT / 'schemas/SCHEMA_BUNDLE_V1.sha256').read_text().split()[0][:16]}…`",
              f"- `Package.resolved` `{_sha(ROOT / 'Package.resolved')}…`; runtime lock "
              f"`{_sha(ROOT / 'analysis/requirements-macos-arm64-py312.lock')}…`",
              f"- Suite evaluation: `{suite['validation_id']}` at {suite['created_wall_time']}", ""]
    return "\n".join(lines) + "\n", decision
